"""havok_diff.py: differential test of lifted functions against the original code.

The reference is the original machine code run in Unicorn (QEMU's x86 core) at
its link addresses; the subject is the same functions lifted by xboxrecomp's
own translator and compiled into a 64-bit DLL over a guest-memory buffer. Both
start every run from the same memory image, registers and x87 argument; return
registers, st(0) and every byte outside the stack are compared afterwards.

(The in-process native harness in tools/conformance cannot run here: a 32-bit
process's low 6 MB -- its stack, heaps and mapped files -- collides with the
XBE's fixed addresses.)

usage: python havok_diff.py gen <va list file> <workdir> [limit]
       python havok_diff.py run <workdir> [-k VA,VA]
Building the DLL between the two: <workdir>/build.cmd (vcvars64).
"""
import ctypes, json, os, re, struct, sys, time

XR = "D:/n64work/halo2/third_party/xboxrecomp"
XBE = "D:/n64work/halo2/dirty/game/default.xbe"
MEM = 0x01000000
CW = int(os.environ.get("HD_CW", "0x027F"), 16)   # x87 control word for both sides                    # 16 MB of guest memory on both sides
SCRATCH, SCRATCH_SIZE = 0x00C00000, 0x4000
THIS = SCRATCH + 0x2000
STACK_LO, STACK_TOP = 0x00D00000, 0x00E00000
TRAMP = 0x00F00000
FP_ARGS = [0.0, 1.0, -1.0, 3.5, -2.25, 1e10, 0.5, 2.0, -0.5, 100.0, 0.25]
S = SCRATCH
ARG_VECTORS = [
    (0, 0, 0, 0), (1, 2, 3, 4), (0xFFFFFFFF, 1, 0, 2),
    (0x40000000, 0x3F800000, 2, 1),
    (S, S + 0x100, 4, 1), (S + 0x40, S + 0x200, 0x10, 2),
    (S, 1, S + 0x80, 0), (S + 0x20, S + 0x20, 8, 0xFFFFFFFF),
    (S + 0x400, S + 0x800, S + 0xC00, 3), (S + 0x1000, 0, S + 0x1400, S + 0x1800),
    (S + 0x300, S + 0x500, 1, S + 0x700),
]

PRELUDE = r'''/* generated by havok_diff.py */
#define RECOMP_GENERATED_CODE 1
#include <stdint.h>
#include <stddef.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include <math.h>
#include <windows.h>
#include "recomp_types.h"
RECOMP_TLS uint32_t g_eax, g_ecx, g_edx, g_esp, g_ebx, g_esi, g_edi;
RECOMP_TLS uint32_t g_seh_ebp, g_ebp;
RECOMP_TLS double g_fp_stack[8]; RECOMP_TLS int g_fp_top;
RECOMP_TLS uint16_t g_fp_control_word = 0x027F; RECOMP_TLS int g_fp_cmp; RECOMP_TLS uint16_t g_fp_cc = 0x4000;
RECOMP_TLS RecompMmx g_mm0, g_mm1, g_mm2, g_mm3, g_mm4, g_mm5, g_mm6, g_mm7;
RECOMP_TLS uint32_t g_recomp_eflags = 0x00000202u;
RECOMP_TLS uint32_t g_recomp_mxcsr = 0x00001F80u;
RECOMP_TLS uint32_t g_fs_base = 0x00FE0000u;   /* a TIB in scratch-free memory */
RECOMP_TLS int g_df;
uint64_t xbox_ReadTimeStampCounter(void) { return 0; }
void recomp_unimpl(const char *text, uint32_t va) { (void)text; (void)va; }
RECOMP_TLS RecompXmm g_xmm0,g_xmm1,g_xmm2,g_xmm3,g_xmm4,g_xmm5,g_xmm6,g_xmm7;
volatile uint32_t g_icall_trace[16]; volatile uint32_t g_icall_trace_idx;
volatile uint64_t g_icall_count;
ptrdiff_t g_xbox_mem_offset;
int g_force_return; uint32_t g_xbox_code_lo = 0x10000, g_xbox_code_hi = 0x600000;
void recomp_icall_fail_log(uint32_t va) { (void)va; RaiseException(0xE0000002u, 0, 0, 0); }
void recomp_icall_not_code_log(uint32_t va) { (void)va; RaiseException(0xE0000002u, 0, 0, 0); }
typedef void (*recomp_func_t)(void);
static recomp_func_t lookup_lifted(uint32_t va);
/* Indirect calls resolve to the lifted set; a target outside it is reported
   as "unresolved" (h_run returns 3), not as a mismatch. */
recomp_func_t recomp_lookup(uint32_t va) { return lookup_lifted(va); }
recomp_func_t recomp_lookup_manual(uint32_t va) { (void)va; return 0; }
recomp_func_t recomp_lookup_kernel(uint32_t va) { (void)va; return 0; }
'''

TAIL = r'''
static uint8_t *g_base;
__declspec(dllexport) uint64_t h_init(void) {
    /* 4 GB reserved so any 32-bit guest address is ours; 16 MB committed.
       A wild pointer lands in the reserve and faults inside __try. */
    g_base = (uint8_t *)VirtualAlloc(NULL, 0x100000000ull, MEM_RESERVE, PAGE_NOACCESS);
    if (!g_base) return 0;
    if (!VirtualAlloc(g_base, MEMSIZE, MEM_COMMIT, PAGE_READWRITE)) return 0;
    g_xbox_mem_offset = (ptrdiff_t)g_base;
    return (uint64_t)(uintptr_t)g_base;
}
__declspec(dllexport) int h_run(uint32_t va, uint32_t cw, uint32_t ecx_, uint32_t esp_, double fparg,
                                uint32_t *regs, double *st0) {
    recomp_func_t f = lookup_lifted(va);
    if (!f) return -1;
    g_fp_cmp = 0; g_fp_cc = 0x4000; g_fp_control_word = (uint16_t)cw;
    memset(g_fp_stack, 0, sizeof g_fp_stack);
    g_fp_top = 7; g_fp_stack[7] = fparg;
    g_eax = g_edx = g_ebx = g_esi = g_edi = 0; g_ecx = ecx_;
    g_seh_ebp = g_ebp = 0; g_esp = esp_;
    memset(&g_xmm0, 0, sizeof g_xmm0); memset(&g_xmm1, 0, sizeof g_xmm1);
    memset(&g_xmm2, 0, sizeof g_xmm2); memset(&g_xmm3, 0, sizeof g_xmm3);
    memset(&g_xmm4, 0, sizeof g_xmm4); memset(&g_xmm5, 0, sizeof g_xmm5);
    memset(&g_xmm6, 0, sizeof g_xmm6); memset(&g_xmm7, 0, sizeof g_xmm7);
    __try { f(); }
    __except (EXCEPTION_EXECUTE_HANDLER) {
        return GetExceptionCode() == 0xE0000002u || GetExceptionCode() == 0xE0000001u ? 3 : 2;
    }
    regs[0] = g_eax; regs[1] = g_edx;
    *st0 = g_fp_stack[g_fp_top & 7];
    return 0;
}
'''


def gen(listfile, wd, limit=5000):
    sys.path.insert(0, XR)
    os.environ["CONF_ONLY"] = listfile
    os.environ["CONF_ANY_RET"] = "1"
    from tools.conformance import xbe_run
    from tools.recomp.disasm import Disassembler
    data, sections, _ = xbe_run.load(XBE)
    entries, needed, closure = xbe_run.find_candidates(data, sections, limit, Disassembler()._cs)
    if os.environ.get("CONF_ALLOW_ICALL") == "1":
        # every listed function, so a virtual call's target is in the set
        funcs = xbe_run.scan(data, sections, Disassembler()._cs,
                             extra={int(t, 16) for t in open(listfile).read().split()})
        want = {va for va, _, _ in needed}
        for t in open(listfile).read().split():
            va = int(t, 16)
            if va in funcs and va not in want:
                needed.append((va, funcs[va].end - va, funcs[va].code)); want.add(va)
    lifted, rejected = xbe_run.lift(data, sections, needed)
    have = {va for va, _, _ in lifted}
    callable_ = [va for va, _, _ in lifted if va in closure and closure[va] <= have]
    os.makedirs(wd, exist_ok=True)
    out = [PRELUDE, f"#define MEMSIZE 0x{MEM:X}ull"]
    defined = {va for va, _, _ in lifted}
    refd = set()
    for _, _, body in lifted:
        refd |= {int(h, 16) for h in re.findall(r"\blifted_([0-9A-Fa-f]{8})\b", body)}
    # sub_ names reached through RECOMP_ABI_CALL(va, sub_X): the lifted copy
    # when there is one, else a stub that reports "unresolved".
    subs = set()
    for _, _, body in lifted:
        subs |= {int(h, 16) for h in re.findall(r"\bsub_([0-9A-Fa-f]{8})\b", body)}
    for va in sorted(subs):
        if va in defined:
            out.append(f"#define sub_{va:08X} lifted_{va:08X}")
        else:
            out.append(f"static void sub_{va:08X}(void) {{ RaiseException(0xE0000001u, 0, 0, 0); }}")
    for va in sorted(defined | refd):
        out.append(f"void lifted_{va:08X}(void);")
    for _, _, body in lifted:
        out.append(body)
    for va in sorted(refd - defined):
        out.append(f"void lifted_{va:08X}(void) {{ RaiseException(0xE0000001u, 0, 0, 0); }}")
    # (lookup_lifted below also serves recomp_lookup for indirect calls)
    out.append("static recomp_func_t lookup_lifted(uint32_t va) { switch (va) {")
    for va in sorted(defined):
        out.append(f"    case 0x{va:08X}u: return lifted_{va:08X};")
    out.append("    default: return 0; } }")
    out.append(TAIL)
    open(os.path.join(wd, "lifted_dll.c"), "w").write("\n".join(out))
    json.dump({"entries": sorted(callable_),
               "sections": [[s.name, s.va, s.vsize, s.raw_off, s.raw_size] for s in sections],
               "rejected": [[va, why[0]] for va, why in rejected]},
              open(os.path.join(wd, "meta.json"), "w"))
    wdw = wd.replace("/", "\\")
    open(os.path.join(wd, "build.cmd"), "w").write(
        "@echo off\r\n"
        "set \"PATH=C:\\Windows\\System32;C:\\Windows;C:\\Program Files (x86)\\Microsoft Visual Studio\\Installer\"\r\n"
        "call \"C:\\Program Files (x86)\\Microsoft Visual Studio\\2022\\BuildTools\\VC\\Auxiliary\\Build\\vcvars64.bat\" >nul\r\n"
        f"cd /d {wdw}\r\n"
        f"cl /nologo /O1 /W0 /LD /I\"{XR}/templates/runtime\" lifted_dll.c /Felifted.dll > build.log 2>&1\r\n"
        "echo BUILD_EXIT=%ERRORLEVEL%\r\n")
    print(f"{len(entries)} entries, {len(needed)} in closure, {len(callable_)} comparable, "
          f"{len(rejected)} rejected -> {wd}")


def seed_scratch():
    b = bytearray()
    for i in range(SCRATCH_SIZE // 4):
        f = float((((i * 37) % 41) - 20) * 0.125)
        w = struct.unpack("<I", struct.pack("<f", f))[0]
        if i % 16 == 3:
            w = i % 5
        b += struct.pack("<I", w)
    return bytes(b)


def run(wd, only=None):
    from unicorn import Uc, UcError, UC_ARCH_X86, UC_MODE_32, UC_PROT_ALL
    from unicorn.x86_const import (UC_X86_REG_EAX, UC_X86_REG_ECX, UC_X86_REG_EDX,
        UC_X86_REG_EBX, UC_X86_REG_ESI, UC_X86_REG_EDI, UC_X86_REG_ESP, UC_X86_REG_EBP)
    meta = json.load(open(os.path.join(wd, "meta.json")))
    dll = ctypes.CDLL(os.path.join(wd, "lifted.dll"))
    dll.h_init.restype = ctypes.c_uint64
    dll.h_run.argtypes = [ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_uint32, ctypes.c_double,
                          ctypes.POINTER(ctypes.c_uint32), ctypes.POINTER(ctypes.c_double)]
    base = dll.h_init()
    assert base, "DLL could not reserve guest memory"
    lmem = (ctypes.c_ubyte * MEM).from_address(base)

    img = bytearray(MEM)
    raw = open(XBE, "rb").read()
    for name, va, vsize, roff, rsize in meta["sections"]:
        if va + rsize <= MEM:
            img[va:va + rsize] = raw[roff:roff + rsize]
    img[SCRATCH:SCRATCH + SCRATCH_SIZE] = seed_scratch()
    # trampoline: finit; fldcw [cw]; fld qword [arg]; call target; store eax, edx, st0
    data_at = TRAMP + 0x100
    struct.pack_into("<H", img, data_at, CW)
    pristine = bytes(img)

    uc = Uc(UC_ARCH_X86, UC_MODE_32)
    uc.mem_map(0, MEM, UC_PROT_ALL)

    def tramp(target):
        c = bytearray(b"\x9B\xDB\xE3")                                   # finit
        c += b"\xD9\x2D" + struct.pack("<I", data_at)                    # fldcw
        c += b"\xDD\x05" + struct.pack("<I", data_at + 8)                # fld qword arg
        # call dword ptr [slot]: the code never changes, so Unicorn's cache of
        # translated blocks cannot run a previous run's target.
        c += b"\xFF\x15" + struct.pack("<I", data_at + 0x20)
        c += b"\xA3" + struct.pack("<I", data_at + 0x10)                 # mov [..], eax
        c += b"\x89\x15" + struct.pack("<I", data_at + 0x14)             # mov [..], edx
        c += b"\xDD\x1D" + struct.pack("<I", data_at + 0x18)             # fstp qword
        return bytes(c)

    entries = meta["entries"]
    if only:
        entries = [v for v in entries if v in only]
    fails, faults, skipped, total, rounding, unresolved = {}, {}, 0, 0, {}, 0
    lo_cmp = [(0, STACK_LO), (STACK_TOP, TRAMP)]          # compared ranges
    t0 = time.time()
    for va in entries:
        for vi, vec in enumerate(ARG_VECTORS):
            fp = FP_ARGS[vi % len(FP_ARGS)]
            # ---- reference
            uc.mem_write(0, pristine)
            code = tramp(va)
            uc.mem_write(TRAMP, code)
            uc.mem_write(data_at + 8, struct.pack("<d", fp))
            uc.mem_write(data_at + 0x20, struct.pack("<I", va))
            sp = STACK_TOP - 64
            uc.mem_write(sp, struct.pack("<4I", *vec))
            for r in (UC_X86_REG_EAX, UC_X86_REG_EDX, UC_X86_REG_EBX, UC_X86_REG_ESI,
                      UC_X86_REG_EDI, UC_X86_REG_EBP):
                uc.reg_write(r, 0)
            uc.reg_write(UC_X86_REG_ECX, THIS)
            uc.reg_write(UC_X86_REG_ESP, sp)
            try:
                uc.emu_start(TRAMP, TRAMP + len(code), timeout=2_000_000, count=3_000_000)
            except UcError:
                skipped += 1
                continue
            # emu_start returning early (count/timeout) leaves eip short of the end
            from unicorn.x86_const import UC_X86_REG_EIP
            if uc.reg_read(UC_X86_REG_EIP) != TRAMP + len(code):
                skipped += 1
                continue
            ref = bytes(uc.mem_read(0, MEM))
            r_eax, r_edx = struct.unpack_from("<II", ref, data_at + 0x10)
            r_st0 = struct.unpack_from("<d", ref, data_at + 0x18)[0]
            # ---- lifted
            ctypes.memmove(base, pristine, MEM)
            lsp = sp - 4
            struct.pack_into("<4I", lmem, sp, *vec)
            struct.pack_into("<I", lmem, lsp, 0xDEADBEEF)
            regs = (ctypes.c_uint32 * 2)()
            st0 = ctypes.c_double()
            rc = dll.h_run(va, CW, THIS, lsp, fp, regs, ctypes.byref(st0))
            total += 1
            if rc == 3:
                unresolved += 1
                continue
            if rc != 0:
                faults.setdefault(va, []).append(vi)
                continue
            got = bytes(lmem)
            why = []
            if regs[0] != r_eax: why.append(f"eax {r_eax:08X}/{regs[0]:08X}")
            if regs[1] != r_edx: why.append(f"edx {r_edx:08X}/{regs[1]:08X}")
            a, b = r_st0, st0.value
            if (a == a or b == b) and not (abs(a - b) <= 1e-6 * max(1.0, abs(a))):
                why.append(f"st0 {a:.9g}/{b:.9g}")
            for lo, hi in lo_cmp:
                if ref[lo:hi] != got[lo:hi]:
                    # first differing dword
                    i = next(i for i in range(lo, hi) if ref[i] != got[i]) & ~3
                    rv, gv = struct.unpack_from("<I", ref, i)[0], struct.unpack_from("<I", got, i)[0]
                    rf, gf = struct.unpack_from("<f", ref, i)[0], struct.unpack_from("<f", got, i)[0]
                    close = rf == rf and gf == gf and abs(rf - gf) <= 1e-5 * max(1.0, abs(rf))
                    why.append(f"mem {i:08X} {rv:08X}/{gv:08X}" + (" (float rounding)" if close else ""))
                    break
            if why:
                if all("rounding" in w for w in why):
                    rounding.setdefault(va, []).append((vi, why))
                else:
                    fails.setdefault(va, []).append((vi, why))
    print(f"{len(entries)} functions, {total} runs compared, {skipped} reference runs skipped "
          f"(fault/timeout), {unresolved} reached untranslated code, {time.time() - t0:.0f} s")
    print(f"MISMATCH {len(fails)} functions | lifted-only fault {len(faults)} | float rounding only {len(rounding)}")
    for va in sorted(fails):
        vi, why = fails[va][0]
        print(f"  FAIL sub_{va:08X} ({len(fails[va])} vectors) vec {vi}: {'; '.join(why)}")
    for va in sorted(faults):
        print(f"  LIFTED FAULT sub_{va:08X} vectors {faults[va]}")
    json.dump({"fails": {f"{k:08X}": v for k, v in fails.items()},
               "faults": {f"{k:08X}": v for k, v in faults.items()}},
              open(os.path.join(wd, "result.json"), "w"), indent=1)


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(sys.argv[2], sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 5000)
    else:
        only = None
        if len(sys.argv) > 4 and sys.argv[3] == "-k":
            only = {int(x, 16) for x in sys.argv[4].split(",")}
        run(sys.argv[2], only)
