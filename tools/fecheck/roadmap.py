"""Where every unfinished game function stands, from four sources:
upstream's byte-match status (config/functions.csv, regenerated by the maintainer's
check.py after every batch), fecheck's latest verdict (WORK/results), snapshot coverage
(snapstore) and the full in-game trace (every RECOMP_FE_OUT fe.bin under the report and
snapshot roots: call counts for all 12,146 game functions).

    python roadmap.py [--decomp <tree>] [--out <dir>]

Writes <out>/roadmap.csv (one row per unmatched game function) and prints the summary.
"""
import argparse, collections, csv, glob, json, os, sys
import common, snapstore
from facts import read_table

NEXT = {
    'byte': 'behaves like retail: needs byte tuning (maintainer check / LTCG convention)',
    'fix': 'differs from retail: fix the behaviour',
    'bench': 'harness cannot run it yet (unbuildable / untestable / crashed)',
    'write': 'no source yet: write a body',
    'recapture': 'runs in game but has no snapshot: recapture with it on the list',
    'unchecked': 'has snapshots but no fecheck verdict yet',
    'reach': 'never executed in any recording: needs new gameplay',
}


def traces():
    counts = collections.Counter(); where = collections.defaultdict(set)
    roots = [os.path.join(common.HALO2, 'reports'), common.SNAPS]
    for r in roots:
        for p in glob.glob(os.path.join(r, '**', 'fe*.bin'), recursive=True):
            try:
                recs = read_table(p)
            except Exception:
                continue
            scen = os.path.relpath(os.path.dirname(p), r).replace(os.sep, '/')
            for va, rec in recs.items():
                c = rec['count'] if isinstance(rec, dict) else rec[0]
                if c:
                    counts[va] += c; where[va].add(scen)
    return counts, where


def verdicts():
    best = {}
    for p in glob.glob(os.path.join(common.WORK, 'results', '*.json')):
        b = os.path.basename(p); va = int(b[:8], 16); t = os.path.getmtime(p)
        if va not in best or t > best[va][0]:
            try:
                best[va] = (t, json.load(open(p)).get('verdict'))
            except Exception:
                pass
    return {v: x[1] for v, x in best.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--decomp', default=common.DECOMP)
    ap.add_argument('--out', default=os.path.join(common.WORK, 'roadmap'))
    a = ap.parse_args()
    rows = list(csv.DictReader(open(os.path.join(a.decomp, 'config', 'functions.csv'))))
    calls = collections.defaultdict(set)
    for x in rows:
        for c in x['calls'].split():
            calls[int(c, 16)].add(int(x['va'], 16))
    counts, where = traces(); ver = verdicts(); sn = snapstore.counts()
    status = {int(x['va'], 16): x['status'] for x in rows}
    out = []
    for x in rows:
        if x['owner'] != 'game' or x['status'] == 'matched':
            continue
        va = int(x['va'], 16); v = ver.get(va); ns = sn.get(va, 0); c = counts.get(va, 0)
        if not x['source']:
            cat = 'write'
        elif ns and v in ('equivalent', 'equivalent_fp'):
            cat = 'byte'
        elif ns and v == 'differs':
            cat = 'fix'
        elif ns and v in ('unbuildable', 'untestable', 'crashed'):
            cat = 'bench'
        elif ns:
            cat = 'unchecked'
        elif c:
            cat = 'recapture'
        else:
            cat = 'reach'
        # for never-run code: the nearest callers that did run, to point at the gameplay that reaches it
        hint = ''
        if cat == 'reach':
            seen, frontier, ran = {va}, [va], []
            for _ in range(3):
                nxt = []
                for f in frontier:
                    for p in calls.get(f, ()):
                        if p in seen: continue
                        seen.add(p)
                        (ran if counts.get(p) else nxt).append(p)
                frontier = nxt
                if ran: break
            hint = ' '.join('%06x' % p for p in sorted(ran)[:4]) or ('no caller' if not calls.get(va) else 'callers never ran')
        out.append({'va': x['va'], 'size': x['size'], 'status': x['status'], 'source': x['source'], 'category': cat,
                    'fecheck': v or '', 'snapshots': ns, 'trace_calls': c,
                    'scenarios': ' '.join(sorted(where.get(va, ())))[:120], 'ran_callers': hint})
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, 'roadmap.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(out[0])); w.writeheader(); w.writerows(out)
    by = collections.Counter(r['category'] for r in out)
    sz = collections.Counter(); [sz.update({r['category']: int(r['size'])}) for r in out]
    game = [x for x in rows if x['owner'] == 'game']
    print('game functions: %d, matched %d (%.1f%%), unfinished %d' % (len(game), sum(x['status'] == 'matched' for x in game),
          100.0 * sum(x['status'] == 'matched' for x in game) / len(game), len(out)))
    print('traced in game (any run): %d of %d game functions' % (sum(1 for x in game if counts.get(int(x['va'], 16))), len(game)))
    for k in ['byte', 'fix', 'bench', 'unchecked', 'recapture', 'write', 'reach']:
        print('  %-10s %5d fns %8d bytes  %s' % (k, by[k], sz[k], NEXT[k]))
    hints = collections.Counter(r['ran_callers'] for r in out if r['category'] == 'reach')
    print('  reach: %d have no caller in the call graph (vtables / callbacks), %d whose callers never ran either'
          % (hints['no caller'], hints['callers never ran']))


if __name__ == '__main__':
    main()
